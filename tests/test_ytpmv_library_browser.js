const assert=require('node:assert/strict');
const path=require('node:path');
async function run(chromium,origin='http://127.0.0.1:8877') {
 const browser=await chromium.launch({headless:true,...(process.env.MRS_TEST_CHROMIUM?{executablePath:process.env.MRS_TEST_CHROMIUM}:{})});
 const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 const entry=id=>page.locator(`[data-entry="${id}"]`);
 try {
  await page.goto(origin+'/ytpmv.html');
  await entry('fixture-song').waitFor();
  assert.equal(await page.locator('#view-editor').isVisible(),false);
  assert.equal(await page.locator('#open-editor').isDisabled(),true);
  await page.locator('.lib-row[data-mid=fixture-song]').click();
  await page.locator('.track').first().waitFor();
  await page.waitForFunction(()=>!document.querySelector('.part[aria-busy=true]'));
  await page.locator('.part[data-id=lead] [data-k=volume-value]').fill('65');
  await page.locator('#open-midi-library').click();
  assert.equal(await page.locator('#track-lanes').isVisible(),false);
  assert.equal(await page.locator('#song-sound').isVisible(),false);
  await entry('fixture-song').getByRole('button',{name:'Rename',exact:true}).click();
  const title='Renamed <img src=x onerror=alert(1)>';
  await page.getByLabel('MIDI title',{exact:true}).fill(title);
  await page.getByRole('button',{name:'Save name',exact:true}).click();
  await page.locator('#lib-status').getByText(`Renamed to ${title}.`,{exact:true}).waitFor();
  assert.equal(await entry('fixture-song').locator('.t').textContent(),title);
  assert.equal(await entry('fixture-song').locator('img').count(),0);
  await page.locator('#open-editor').click();
  assert.equal(await page.locator('#song-title').textContent(),title);
  assert.equal(await page.locator('.part[data-id=lead] [data-k=volume-value]').inputValue(),'65');
  await page.reload();await page.locator('.track').first().waitFor();
  assert.equal(await page.locator('#song-title').textContent(),title);
  await page.locator('#open-midi-library').click();
  await page.locator('#lib-search').fill('Renamed');
  assert.equal(await page.locator('.lib-entry').count(),1);
  await page.locator('#lib-search').fill('');
  await page.route('**/api/ytpmv/midi/fixture-song',route=>route.request().method()==='PATCH'?route.fulfill({status:500,json:{detail:'fixture rename failed'}}):route.continue());
  await entry('fixture-song').getByRole('button',{name:'Rename',exact:true}).click();
  await page.getByLabel('MIDI title',{exact:true}).fill('Keep my draft');
  await page.getByRole('button',{name:'Save name',exact:true}).click();
  await page.locator('#lib-status').getByText(/Could not rename/).waitFor();
  assert.equal(await page.getByLabel('MIDI title',{exact:true}).inputValue(),'Keep my draft');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.unroute('**/api/ytpmv/midi/fixture-song');
  await page.screenshot({path:path.resolve('output/ytpmv-smoke/midi-library-desktop.png'),fullPage:true});
  await page.setViewportSize({width:320,height:850});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await entry('fixture-second').getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await entry('fixture-second').count(),1);
  await entry('fixture-second').getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Delete MIDI',exact:true}).click();
  await entry('fixture-second').waitFor({state:'detached'});
  await entry('fixture-song').getByRole('button',{name:'Delete',exact:true}).click();
  await page.getByRole('button',{name:'Delete MIDI',exact:true}).click();
  await entry('fixture-song').waitFor({state:'detached'});
  assert.equal(await page.locator('#open-editor').isDisabled(),true);
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('ytpmv-last-midi'))),null);
  assert.equal(await page.evaluate(()=>Object.keys(JSON.parse(localStorage.getItem('ytpmv-projects'))).length),0);
  await page.locator('#lib-list').getByText(/No MIDI files yet/).waitFor();
  await page.reload();await page.locator('#lib-list').getByText(/No MIDI files yet/).waitFor();
  assert.equal(await page.locator('#view-library').isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log('PASS MIDI library: separate tabs, editor state preservation, inline rename/reload, escaped names, failure recovery, delete/cancel, active-song cleanup, empty state, mobile');
 }finally{await browser.close();}
}
module.exports=run;
if(require.main===module)run(require('playwright').chromium).catch(e=>{console.error(e);process.exitCode=1;});
